/*
# Create Incident & Accident Log and Investigation Register

1. New Tables
- `incident_reports` stores the incident register and the complete investigation form.
- `id` is the record identifier.
- `incident_id` is the human-readable incident report number.
- `occurred_at` stores the date and time of occurrence.
- `department`, `classification`, and `severity` identify the event.
- `person_name`, `location`, `description`, and `root_cause` store investigation details.
- `lost_work_days` and `cost_impact` store impact information.
- `investigator_signature` stores the named investigator.
- `status` tracks whether the investigation is open, under investigation, or closed.
- `corrective_action` stores the agreed corrective resolution.
- `created_by`, `created_at`, and `updated_at` provide audit context.

2. Security
- Row level security is enabled.
- Authenticated application users may read, create, update, and delete shared incident records.
- The app already requires sign-in through its route guard, so anonymous access is not granted.

3. Important Notes
- This is a new table and does not modify or remove any existing data.
- The human-readable incident number is unique and can be generated by the form.
*/

CREATE TABLE IF NOT EXISTS public.incident_reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id text NOT NULL UNIQUE,
  occurred_at timestamptz NOT NULL,
  department text NOT NULL,
  classification text NOT NULL,
  severity text NOT NULL,
  person_name text,
  location text,
  description text NOT NULL,
  root_cause text NOT NULL,
  lost_work_days numeric NOT NULL DEFAULT 0 CHECK (lost_work_days >= 0),
  cost_impact numeric NOT NULL DEFAULT 0 CHECK (cost_impact >= 0),
  investigator_signature text,
  status text NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Under Investigation', 'Closed')),
  corrective_action text,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.incident_reports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "authenticated_read_incident_reports" ON public.incident_reports;
CREATE POLICY "authenticated_read_incident_reports" ON public.incident_reports
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "authenticated_insert_incident_reports" ON public.incident_reports;
CREATE POLICY "authenticated_insert_incident_reports" ON public.incident_reports
  FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "authenticated_update_incident_reports" ON public.incident_reports;
CREATE POLICY "authenticated_update_incident_reports" ON public.incident_reports
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "authenticated_delete_incident_reports" ON public.incident_reports;
CREATE POLICY "authenticated_delete_incident_reports" ON public.incident_reports
  FOR DELETE TO authenticated USING (true);

CREATE INDEX IF NOT EXISTS incident_reports_occurred_at_idx ON public.incident_reports (occurred_at DESC);
CREATE INDEX IF NOT EXISTS incident_reports_status_idx ON public.incident_reports (status);
